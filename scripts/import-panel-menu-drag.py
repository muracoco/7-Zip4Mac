"""Import official portable file-menu filtering and drag-effect bodies."""
from upstream_support import VERSION, source_hash, aggregate_hash, artifact_hash, output_root, write_generated
import argparse
import hashlib
import re
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('source', type=Path)
args = parser.parse_args()
base = args.source / 'CPP/7zip/UI/FileManager'
hashes = {
    'MyLoadMenu.cpp': source_hash('CPP/7zip/UI/FileManager/MyLoadMenu.cpp'),
    'PanelDrag.cpp': source_hash('CPP/7zip/UI/FileManager/PanelDrag.cpp'),
    'resource.h': source_hash('CPP/7zip/UI/FileManager/resource.h'),
}
texts = {}
for name, digest in hashes.items():
    raw = (base / name).read_bytes()
    if hashlib.sha256(raw).hexdigest() != digest:
        parser.error('Unsupported official source: ' + name)
    texts[name] = raw.decode().replace('\r\n', '\n')

def function(text, signature):
    start = text.index(signature)
    cursor = text.index('{', start) + 1
    depth = 1
    while depth:
        depth += (text[cursor] == '{') - (text[cursor] == '}')
        cursor += 1
    return text[start:cursor]

out = output_root() / 'src/upstream'
header = '// Copyright (C) 1999-2026 Igor Pavlov. GNU LGPL-2.1-or-later.\n'
header += f'// Official 7-Zip {VERSION}; generated by scripts/import-panel-menu-drag.py.\n'
for name, digest in hashes.items():
    header += '// ' + name + ' SHA-256: ' + digest + '\n'
body = function(texts['MyLoadMenu.cpp'], 'void CFileMenu::Load(HMENU hMenu, unsigned startPos)')
# Copy the source action adapters into the destination's Qt adapter.
body = body.replace('  CMenu destMenu;', '  CMenu destMenu = g_FileMenu;')
arrays = texts['MyLoadMenu.cpp'][texts['MyLoadMenu.cpp'].index('static const unsigned g_Zvc_IDs[]'):texts['MyLoadMenu.cpp'].index('void CFileMenu::Load(')]
ids = re.findall(r'^#define\s+(IDM_\w+)\s+(\d+)\s*$', texts['resource.h'], re.M)
write_generated(out / 'PanelMenu.inc', header + '\n' + ''.join('constexpr unsigned ' + name + ' = ' + number + ';\n' for name, number in ids) + '\n' + arrays + body)
drag = texts['PanelDrag.cpp']
labels = '\n'.join('constexpr unsigned ' + name + ' = ' + re.search(r'^#define\s+' + name + r'\s+(\d+)', texts['resource.h'], re.M).group(1) + ';' for name in ('IDS_COPY', 'IDS_MOVE', 'IDS_COPY_TO'))
# The Explorer string IDs are also fixed in the pinned official language
# resources used by the port: archive=2321, compress=2324.
labels += '\nconstexpr unsigned IDS_CONTEXT_COMPRESS = 2324;\n'
write_generated(out / 'PanelDrag.inc', header + '\n' + labels + '\n' + function(drag, 'namespace NDragMenu') + '\n\n' + function(drag, 'static DWORD GetEffect_ForKeys(DWORD keyState)') + '\n\n' + function(drag, 'DWORD CDropTarget::GetEffect(DWORD keyState, POINTL /* pt */, DWORD allowedEffect) const') + '\n')
