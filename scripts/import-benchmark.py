"""Import pinned official Benchmark arithmetic; leave upstream files intact."""
from upstream_support import VERSION, source_hash, aggregate_hash, artifact_hash, output_root, write_generated
import hashlib
import pathlib
import sys

root = output_root()
source = pathlib.Path(sys.argv[1]) / 'CPP/7zip/UI'
hashes = {
    'GUI/BenchmarkDialog.cpp': source_hash('CPP/7zip/UI/GUI/BenchmarkDialog.cpp'),
    'Common/Bench.cpp': source_hash('CPP/7zip/UI/Common/Bench.cpp'),
}
texts = {}
for path, expected in hashes.items():
    raw = (source / path).read_bytes()
    if hashlib.sha256(raw).hexdigest() != expected:
        raise SystemExit(f'Not the pinned official {VERSION} source: ' + path)
    texts[path] = raw.decode('utf-8').replace('\r\n', '\n')

def body(text, signature, suffix=''):
    start = text.index(signature)
    cursor = text.index('{', start) + 1
    depth = 1
    while depth:
        depth += (text[cursor] == '{') - (text[cursor] == '}')
        cursor += 1
    return text[start:cursor] + suffix

def write(name, origin, chunks):
    header = ('// ' + origin + '\n'
              '// Copyright (C) 1999-2026 Igor Pavlov. GNU LGPL-2.1-or-later.\n'
              f'// Generated by scripts/import-benchmark.py from official 7-Zip {VERSION}.\n'
              '// Original arithmetic bodies retained; Win32 controls omitted.\n'
              '// Original source SHA-256: ' + hashes[origin] + '\n\n')
    path = root / 'src/upstream' / name
    write_generated(path, header + '\n\n'.join(chunks) + '\n', encoding='utf-8')
    print(path)

gui = texts['GUI/BenchmarkDialog.cpp']
macro = gui[gui.index('#define UINT_TO_STR_3'):gui.index('static WCHAR *NumberToDot3')].strip()
write('BenchmarkGuiMath.inc', 'GUI/BenchmarkDialog.cpp', [
    body(gui, 'struct CTotalBenchRes2:', ';'), macro,
    *[body(gui, signature) for signature in [
        'static WCHAR *NumberToDot3(', 'static UInt64 GetMips(',
        'static UInt64 GetUsagePercents(', 'static UInt32 GetRating(',
        'static void AddUsageString(', 'static void Add_Dot3String(',
        'static void AddRatingString(', 'static void AddRatingsLine(']],
])
common = texts['Common/Bench.cpp']
write('BenchmarkMemory.inc', 'Common/Bench.cpp', [
    'static const size_t kAdditionalSize = (size_t)1 << 16;',
    'static const size_t kCompressedAdditionalSize = (size_t)1 << 10;',
    '#define kLzmaMaxDictSize ((UInt32)15 << 28)',
    *[body(common, signature) for signature in [
        'static size_t GetBenchCompressedSize(', 'static inline UInt64 GetLZMAUsage(',
        'UInt64 GetBenchMemoryUsage(']],
])
